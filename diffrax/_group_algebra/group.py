import functools

import numpy as np


class Group:
    """A finite group given by its Cayley table.

    Elements are numbered `0, ..., n - 1` and `kaili[i, j]` is the number of the
    product `g_i g_j`.

    **Arguments:**

    - `kaili`: integer array of shape `(n, n)`, the Cayley (multiplication) table.
    - `check`: whether to check that `kaili` really is the table of a group. This
        costs `O(n^3)` time.
    """

    def __init__(self, kaili, check: bool = True):
        kaili = np.asarray(kaili)
        if kaili.ndim != 2 or kaili.shape[0] != kaili.shape[1]:
            raise ValueError("The Cayley table must be a square matrix.")
        if not np.issubdtype(kaili.dtype, np.integer):
            raise ValueError("The Cayley table must contain integers.")
        n = kaili.shape[0]
        if n == 0:
            raise ValueError("A group must have at least one element.")
        if kaili.min() < 0 or kaili.max() >= n:
            raise ValueError("Cayley table entries must lie in `0, ..., n - 1`.")
        self.kaili = kaili.astype(np.int64)
        self.n = n

        elements = np.arange(n)
        if check:
            if not (np.sort(self.kaili, axis=0) == elements[:, None]).all():
                raise ValueError("Cayley table is not a Latin square.")
            if not (np.sort(self.kaili, axis=1) == elements[None, :]).all():
                raise ValueError("Cayley table is not a Latin square.")
            for a in range(n):
                if not (self.kaili[self.kaili[a]] == self.kaili[a][self.kaili]).all():
                    raise ValueError("Cayley table is not associative.")

        identities = np.flatnonzero((self.kaili == elements).all(axis=1))
        if len(identities) != 1:
            raise ValueError("Cayley table has no identity element.")
        self.ed = int(identities[0])
        self.inv = np.argmax(self.kaili == self.ed, axis=1)
        if not (self.kaili[elements, self.inv] == self.ed).all():
            raise ValueError("Cayley table has elements without inverses.")

    def __len__(self) -> int:
        return self.n

    @classmethod
    def cyclic(cls, n: int) -> "Group":
        """The cyclic group `Z_n`, with element `k` standing for `k mod n`."""
        if n < 1:
            raise ValueError("`n` must be positive.")
        elements = np.arange(n)
        return cls((elements[:, None] + elements[None, :]) % n, check=False)

    @classmethod
    def from_permutations(cls, generators) -> "Group":
        """The group generated by permutations of `0, ..., m - 1`, each given as the
        tuple of images `(p(0), ..., p(m - 1))`. Products compose right to left:
        `(pq)(k) = p(q(k))`. Element 0 is the identity, and element `i + 1` is
        `generators[i]` unless that was already listed.
        """
        generators = [tuple(int(k) for k in g) for g in generators]
        if len(generators) == 0:
            raise ValueError("At least one generator is needed.")
        size = len(generators[0])
        for g in generators:
            if len(g) != size or sorted(g) != list(range(size)):
                raise ValueError(f"{g} is not a permutation of 0, ..., {size - 1}.")
        identity = tuple(range(size))
        elements = [identity]
        index = {identity: 0}
        for g in generators:
            if g not in index:
                index[g] = len(elements)
                elements.append(g)
        i = 0
        while i < len(elements):
            for g in generators:
                product = tuple(elements[i][k] for k in g)
                if product not in index:
                    index[product] = len(elements)
                    elements.append(product)
            i += 1
        table = np.array(
            [[index[tuple(p[k] for k in q)] for q in elements] for p in elements]
        )
        return cls(table, check=False)

    @functools.cached_property
    def _classes(self):
        def conjugates(g):
            return np.unique(self.kaili[self.kaili[:, g], self.inv])

        class_of = np.full(self.n, -1, dtype=np.int64)
        classes = []
        order = np.concatenate([[self.ed], np.delete(np.arange(self.n), self.ed)])
        for g in order:
            if class_of[g] < 0:
                orbit = conjugates(g)
                class_of[orbit] = len(classes)
                classes.append(orbit)
        return classes, class_of

    def conjugate(self) -> list[np.ndarray]:
        """The conjugacy classes, as a list of arrays of element numbers. Class 0 is
        always `{e}`.
        """
        return self._classes[0]

    @property
    def class_of(self) -> np.ndarray:
        """`class_of[g]` is the number of the conjugacy class containing `g`."""
        return self._classes[1]

    @property
    def class_sizes(self) -> np.ndarray:
        return np.array([len(c) for c in self.conjugate()])

    @functools.cached_property
    def class_constants(self) -> np.ndarray:
        """Array `a` of shape `(h, h, h)` with `C_i C_j = sum_k a[i, j, k] C_k`, where
        `C_i` is the sum of the elements of class `i` in the group algebra.

        Equivalently `a[i, j, k]` counts the pairs `(x, y)` with `x` in class `i`,
        `y` in class `j` and `xy = z`, for any fixed `z` in class `k`.
        """
        classes = self.conjugate()
        h = len(classes)
        a = np.zeros((h, h, h), dtype=np.int64)
        for k, c in enumerate(classes):
            z = c[0]
            y = self.kaili[self.inv, z]  # y = x^{-1} z, so that xy = z.
            np.add.at(a[:, :, k], (self.class_of, self.class_of[y]), 1)
        return a

    def character_table(self, seed: int = 0) -> np.ndarray:
        """The character table, of shape `(h, h)`: row `r` is the irreducible
        character `r`, column `k` is its value on conjugacy class `k`.

        Computed by Burnside's algorithm: the central characters
        `w_k = |C_k| chi(C_k) / chi(e)` are the common eigenvectors of the matrices
        `M_i[j, k] = a[i, j, k]`, which we find by diagonalising a random linear
        combination of them.

        Row 0 is the trivial character, and rows are sorted by degree.
        """
        return self._character_table(seed)

    @functools.cache
    def _character_table(self, seed: int) -> np.ndarray:
        sizes = self.class_sizes
        a = self.class_constants
        h = len(sizes)
        rng = np.random.default_rng(seed)
        for _ in range(10):
            coeffs = rng.standard_normal(h)
            matrix = np.einsum("i,ijk->jk", coeffs, a).astype(np.float64)
            eigvals, eigvecs = np.linalg.eig(matrix)
            gaps = np.abs(eigvals[:, None] - eigvals[None, :])
            gaps[np.diag_indices(h)] = np.inf
            scale = max(1.0, np.abs(eigvals).max())
            if h == 1 or gaps.min() > 1e-6 * scale:
                break
        else:
            raise RuntimeError("Could not separate the irreducible characters.")

        rows = []
        for v in eigvecs.T:
            w = v / v[0]
            degree = np.sqrt(self.n / np.sum(np.abs(w) ** 2 / sizes))
            if abs(degree - round(degree)) > 1e-6:
                raise RuntimeError("Character degree is not an integer.")
            rows.append(round(degree) * w / sizes)
        table = np.array(rows)
        table = _clean(table)

        key = [(round(row[0].real), np.abs(row - 1).sum()) for row in table]
        table = table[sorted(range(h), key=lambda r: key[r])]

        gram = (table * sizes) @ table.conj().T
        if not np.allclose(gram, self.n * np.eye(h), atol=1e-6 * self.n):
            raise RuntimeError("Computed characters are not orthonormal.")
        return table

    def degrees(self) -> np.ndarray:
        """The degrees (dimensions) of the irreducible representations, in the same
        order as the rows of `character_table`.
        """
        return np.round(self.character_table()[:, 0].real).astype(np.int64)

    def characters(self) -> np.ndarray:
        """The irreducible characters as functions on elements: array of shape
        `(h, n)` with `characters()[r, g] = chi_r(g)`.
        """
        return self.character_table()[:, self.class_of]

    def frobenius_schur(self) -> np.ndarray:
        """The Frobenius--Schur indicator `(1/n) sum_g chi(g^2)` of each irreducible
        character: `1` for real, `0` for complex and `-1` for quaternionic type.
        """
        squares = self.kaili[np.arange(self.n), np.arange(self.n)]
        nu = self.characters()[:, squares].sum(axis=1) / self.n
        return np.round(nu.real).astype(np.int64)

    def regular_representation(self, g: int) -> np.ndarray:
        """The matrix of `g` in the left regular representation: the permutation
        matrix sending basis vector `e_b` to `e_{gb}`.
        """
        matrix = np.zeros((self.n, self.n))
        matrix[self.kaili[g], np.arange(self.n)] = 1
        return matrix

    def irreducible_representations(self, seed: int = 0) -> list[np.ndarray]:
        """Unitary matrices of all irreducible representations, in the same order as
        the rows of `character_table`. Entry `r` has shape `(n, d_r, d_r)`, with
        `[g]` the matrix of element `g`.

        Computed inside the left regular representation, following Dixon:

        1. Project onto the isotypic component of `chi` with the central idempotent
            `e = (d/n) sum_g conj(chi(g)) g`. This is a subspace of dimension `d^2`.
        2. Pick a random hermitian operator that commutes with the group (a random
            element of the right regular representation) and restrict it to that
            subspace. Each of its eigenspaces is a copy of the irreducible
            representation; take one.
        """
        return self._irreducible_representations(seed)

    @functools.cache
    def _irreducible_representations(self, seed: int) -> list[np.ndarray]:
        n = self.n
        chars = self.characters()
        rng = np.random.default_rng(seed)
        left_shift = self.kaili[self.inv]
        quotient = self.kaili[:, self.inv]

        r = rng.standard_normal(n) + 1j * rng.standard_normal(n)
        r = r + r[self.inv].conj()
        commutant = r[self.kaili[self.inv]]

        reps = []
        for chi, d in zip(chars, self.degrees()):
            if d == 1:
                reps.append(chi.reshape(n, 1, 1).astype(np.complex128))
                continue
            projector = (d / n) * chi[quotient].conj()
            sketch = projector @ (
                rng.standard_normal((n, d * d)) + 1j * rng.standard_normal((n, d * d))
            )
            basis, _ = np.linalg.qr(sketch)
            restricted = basis.conj().T @ commutant @ basis
            restricted = (restricted + restricted.conj().T) / 2
            eigvals, eigvecs = np.linalg.eigh(restricted)
            spread = np.abs(eigvals).max() + 1
            if eigvals[d] - eigvals[d - 1] < 1e-8 * spread:
                raise RuntimeError("Could not split the isotypic component.")
            u = basis @ eigvecs[:, :d]
            rep = np.empty((n, d, d), dtype=np.complex128)
            u_conj_t = u.conj().T
            for g in range(n):
                rep[g] = u_conj_t @ u[left_shift[g]]
            reps.append(_clean(rep))

        for chi, rep in zip(chars, reps):
            if not np.allclose(np.trace(rep, axis1=1, axis2=2), chi, atol=1e-6):
                raise RuntimeError("Representation does not match its character.")
        return reps

    def check_representation(self, rep: np.ndarray, atol: float = 1e-8) -> bool:
        """Whether `rep` (shape `(n, d, d)`) is a unitary representation:
        `rep[gh] = rep[g] @ rep[h]` for all `g, h`, and every `rep[g]` is unitary.
        """
        rep = np.asarray(rep)
        for g in range(self.n):
            if not np.allclose(rep[g] @ rep, rep[self.kaili[g]], atol=atol):
                return False
        eye = np.eye(rep.shape[1])
        gram = np.einsum("gji,gjk->gik", rep.conj(), rep)
        return bool(np.allclose(gram, eye, atol=atol))


def _clean(x: np.ndarray, atol: float = 1e-10) -> np.ndarray:
    x = np.array(x, dtype=np.complex128)
    x.real[np.abs(x.real) < atol] = 0
    x.imag[np.abs(x.imag) < atol] = 0
    return x
